"""
DislocationDynamicsNet: Second-order neural policy network.
Ingests the orthogonal residual series e_t in R^{423} generated by cmbr/engine/projector.py
and outputs continuous portfolio tilt weights optimized directly for Net Sharpe ratio.
"""
import torch
import torch.nn as nn

class DislocationDynamicsNet(nn.Module):
    def __init__(self, n_assets: int = 423, hidden_dim: int = 64):
        super().__init__()
        self.n_assets = n_assets
        self.hidden_dim = hidden_dim
        
        # Temporal encoder over rolling residual sequence
        self.temporal = nn.GRU(
            input_size=n_assets,
            hidden_size=hidden_dim,
            batch_first=True
        )
        
        # Policy head outputting continuous portfolio tilt weights in [-1, 1]
        self.policy_head = nn.Sequential(
            nn.Linear(hidden_dim, n_assets),
            nn.Tanh()
        )

    def forward(self, residual_sequence: torch.Tensor) -> torch.Tensor:
        """
        Forward pass.
        Args:
            residual_sequence: [Batch, Lookback, n_assets]
        Returns:
            raw_weights: [Batch, n_assets] with values in [-1, 1]
        """
        out, _ = self.temporal(residual_sequence)
        raw_weights = self.policy_head(out[:, -1, :])
        return raw_weights

    @staticmethod
    def project_dollar_neutral(raw_weights: torch.Tensor, max_gross_leverage: float = 1.0) -> torch.Tensor:
        """
        Differentiable dollar-neutral and gross-leverage projection:
        1. Center weights around mean to guarantee sum(w) == 0 (dollar neutrality)
        2. Scale by L1 norm to bound sum(|w|) <= max_gross_leverage
        """
        # Center across asset dimension (dim=-1)
        mean_w = raw_weights.mean(dim=-1, keepdim=True)
        w_centered = raw_weights - mean_w

        # L1 norm scaling
        l1_norm = torch.sum(torch.abs(w_centered), dim=-1, keepdim=True) + 1e-8
        weights = (w_centered / l1_norm) * max_gross_leverage
        return weights
